CREATE TABLE IF NOT EXISTS localizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloco TEXT NOT NULL,
    local TEXT NOT NULL,
    descricao TEXT
);

CREATE TABLE IF NOT EXISTS equipamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_patrimonio TEXT NOT NULL,
    identificacao TEXT NOT NULL,
    marca TEXT,
    modelo TEXT,
    observacao TEXT,
    estado TEXT NOT NULL CHECK (estado IN ('DISPONIVEL', 'EM_USO', 'EM_MANUTENCAO', 'BAIXADO')),
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    localizacao_id BIGINT NOT NULL REFERENCES localizacao(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_equipamento_patrimonio
    ON equipamento (LOWER(TRIM(numero_patrimonio)));

CREATE TABLE IF NOT EXISTS movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL REFERENCES equipamento(id),
    origem_id BIGINT NOT NULL REFERENCES localizacao(id),
    destino_id BIGINT NOT NULL REFERENCES localizacao(id),
    data_hora TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    observacao TEXT,
    CHECK (origem_id <> destino_id)
);

CREATE TABLE IF NOT EXISTS manutencao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL REFERENCES equipamento(id),
    tipo TEXT NOT NULL CHECK (tipo IN ('PREVENTIVA', 'CORRETIVA')),
    data_inicio DATE NOT NULL,
    data_fim DATE,
    descricao TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('ABERTA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    observacao TEXT,
    CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CHECK (status <> 'CONCLUIDA' OR data_fim IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS baixa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL UNIQUE REFERENCES equipamento(id),
    data DATE NOT NULL,
    motivo TEXT NOT NULL,
    observacao TEXT
);

CREATE INDEX IF NOT EXISTS ix_movimentacao_equipamento ON movimentacao (equipamento_id, id);
CREATE INDEX IF NOT EXISTS ix_manutencao_equipamento ON manutencao (equipamento_id, id);
