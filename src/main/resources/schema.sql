CREATE TABLE IF NOT EXISTS categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    CONSTRAINT uq_categoria_nome UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS localizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloco VARCHAR(80) NOT NULL,
    local VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    CONSTRAINT uq_localizacao_bloco_local UNIQUE (bloco, local)
);

CREATE TABLE IF NOT EXISTS equipamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_patrimonio VARCHAR(80) NOT NULL UNIQUE,
    identificacao VARCHAR(160) NOT NULL,
    marca VARCHAR(100),
    modelo VARCHAR(100),
    observacao VARCHAR(1000),
    estado VARCHAR(30) NOT NULL,
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    localizacao_atual_id BIGINT NOT NULL REFERENCES localizacao(id)
);

CREATE TABLE IF NOT EXISTS movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL REFERENCES equipamento(id),
    localizacao_origem_id BIGINT NOT NULL REFERENCES localizacao(id),
    localizacao_destino_id BIGINT NOT NULL REFERENCES localizacao(id),
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS manutencao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL REFERENCES equipamento(id),
    tipo VARCHAR(30) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    descricao VARCHAR(1000) NOT NULL,
    status VARCHAR(30) NOT NULL,
    observacao VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS baixa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL UNIQUE REFERENCES equipamento(id),
    data DATE NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    observacao VARCHAR(1000)
);

CREATE INDEX IF NOT EXISTS idx_equipamento_categoria ON equipamento(categoria_id);
CREATE INDEX IF NOT EXISTS idx_equipamento_localizacao ON equipamento(localizacao_atual_id);
CREATE INDEX IF NOT EXISTS idx_movimentacao_equipamento ON movimentacao(equipamento_id);
CREATE INDEX IF NOT EXISTS idx_manutencao_equipamento ON manutencao(equipamento_id);
